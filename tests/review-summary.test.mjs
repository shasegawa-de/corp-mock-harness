import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync,mkdirSync,rmSync,writeFileSync,readFileSync} from 'node:fs';
import {join,resolve} from 'node:path';
import {tmpdir} from 'node:os';
import {reviewSummary,sealVisualScores,FIELDS} from '../scripts/review-summary.mjs';
const root=resolve(import.meta.dirname,'..');
test('12 blinded scores remain private; report retains per-axis means and hard fails',()=>{
  const dir=mkdtempSync(join(tmpdir(),'corp-mock-qa-test-')),blind=join(dir,'blind');
  mkdirSync(blind,{mode:0o700});
  const arms=['mm1-a','mm1-b','mm1-c','mm2-a','mm2-b','mm2-c'];
  const mapping=arms.flatMap((arm,i)=>[1,2].map(trial=>({blind_id:'R'+String(i*2+trial).padStart(2,'0'),arm,trial})));
  writeFileSync(join(dir,'mapping-private.json'),JSON.stringify(mapping));
  const rows=mapping.map((x,i)=>[x.blind_id,'PASS','PASS',i===0?'FAIL':'PASS','PASS','2','1','2','0','','"some, note"'].join(','));
  const sheet=join(blind,'scores.csv');
  writeFileSync(sheet,FIELDS.join(',')+'\n'+rows.join('\n')+'\n');
  try {
    const initial=reviewSummary(root,dir);
    assert.equal(initial.visual_complete,true);
    assert.equal(initial.fidelity_complete,false);
    assert.equal(initial.sealed,false);
    assert.deepEqual(initial.arms,[],'Do not leak arm averages before the visual seal');
    assert.equal(initial.complete,false);
    const mark=sealVisualScores(root,dir);
    assert.equal(mark.records,12);
    assert.throws(()=>sealVisualScores(root,dir),/already been sealed/);
    const before=reviewSummary(root,dir);
    assert.equal(before.sealed,true);
    assert.equal(before.complete,false);
    assert.equal(before.arms[0].hard_fail,1);
    const source=readFileSync(sheet,'utf8');
    const afterUnblind=source.replaceAll(',0,,"some, note"',',0,1,"some, note"');
    writeFileSync(sheet,afterUnblind);
    const report=reviewSummary(root,dir);
    assert.equal(report.complete,true);
    assert.equal(report.fidelity_complete,true);
    assert.equal(report.arms[0].means.lighting_0_2,0);
    assert.equal(report.arms[1].hard_fail,0);
    assert.equal(report.arms[5].reviewed,2);
    writeFileSync(sheet,afterUnblind.replace('R01,PASS','R01,UNKNOWN'));
    assert.throws(()=>reviewSummary(root,dir),/Incomplete hard-gate/);
    writeFileSync(sheet,afterUnblind.replace('R01,PASS,PASS','R01,PASS,'));
    assert.throws(()=>reviewSummary(root,dir),/Incomplete hard-gate/);
    writeFileSync(sheet,afterUnblind.replace('R01,PASS,PASS,FAIL,PASS,2,1','R01,PASS,PASS,FAIL,PASS,2,0'));
    assert.throws(()=>reviewSummary(root,dir),/Sealed visual review has been modified/);
    writeFileSync(sheet,afterUnblind);
    const invalid=mapping.map(x=>({...x}));
    invalid[11]={...invalid[11],arm:'mm1-a',trial:1};
    writeFileSync(join(dir,'mapping-private.json'),JSON.stringify(invalid));
    assert.throws(()=>reviewSummary(root,dir),/Invalid or incomplete identity mapping/);
  } finally {rmSync(dir,{recursive:true,force:true});}
});
